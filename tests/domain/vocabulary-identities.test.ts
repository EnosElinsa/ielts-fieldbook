test('fixed mapping covers released identities and preserves every entry and sense byte for byte', () => {
  const original = JSON.parse(execFileSync('git',['show','HEAD:public/vocabulary-catalog.json'],{encoding:'utf8',maxBuffer:30*1024*1024}));
  const current = JSON.parse(readFileSync('public/vocabulary-catalog.json','utf8'));
  expect(VOCABULARY_IDENTITIES.books).toHaveLength(6);
  expect(VOCABULARY_IDENTITIES.units).toHaveLength(206);
  expect(VOCABULARY_IDENTITIES.memberships).toHaveLength(9205);
  expect(new Set(VOCABULARY_IDENTITIES.memberships.map(row=>row.id)).size).toBe(9205);
  expect(current.entries).toEqual(original.entries);
  expect(current.memberships.map((row:any)=>row.entryId)).toEqual(original.memberships.map((row:any)=>row.entryId));
  expect(current.units.map((row:any)=>row.sourceUnitId)).toEqual(original.units.map((row:any)=>row.sourceUnitId));
  expect(normalizeVocabularyIdentities(original)).toEqual(current);
});
test('v11 import and twice-run v12 migration preserve content, evidence, dates and record counts', () => {
  const sourceRecord={id:'21795',book_id:'10174',book_hierarchy_id:'21795',correct_rate:'80',text:'guixue:10174'};
  const legacy={...emptyState(),schemaVersion:11,wordbookEnrollments:[{id:'import-enrollment:guixue:10174',bookId:'guixue:10174'}],wordbookProgress:[{id:'guixue-progress:owner:10174:21795',bookId:'guixue:10174',unitId:'21795',sourceRecord,completedEntryIds:['ve-x']}],vocabularyEvidence:[{id:'e',entryId:'ve-x',senseId:'sense',bookId:'guixue:10174',unitId:'21795',response:'guixue:10174 21795',quote:'21795',score:7,occurredAt:'2020-01-01',sourceRecord}],plans:[{id:'p',kind:'vocabulary',target:{bookId:'guixue:10174',unitId:'21795',cards:[{entryId:'ve-x',senseId:'sense'}]},description:'guixue:10174'}]};
  const migrated=migrateState(legacy);
  expect(STATE_VERSION).toBe(12);
  expect(migrateState(migrated)).toEqual(migrated);
  expect(persistShape(legacy).wordbookProgress[0]).toMatchObject({id:'imported-progress:owner:'+unitId,bookId,unitId,sourceRecord});
  expect(migrated.vocabularyEvidence[0]).toMatchObject({...legacy.vocabularyEvidence[0],bookId,unitId});
  expect(migrated.plans[0].description).toBe('guixue:10174');
  expect(mergeBackup(emptyState(),legacy).vocabularyEvidence).toEqual(migrated.vocabularyEvidence);
  expect(vocabularyGroupProgress(migrated,{id:unitId,bookId,entryIds:['ve-x']})).toBe('Studied');
  expect(getLearnedVocabularyIds(migrated).has('ve-x')).toBe(true);
  expect(legacy.wordbookProgress[0].unitId).toBe('21795');
});
test('only structural fields migrate, including numeric-looking content and answer keys', () => {
  const input={id:'10174',text:'21795',answers:{'21795':{response:'guixue:10174'}},responses:{'10174':'21795'},sourceRecord:{id:'21795',bookId:'guixue:10174'},bookId:'guixue:10174',unitId:'21795'};
  expect(normalizeVocabularyIdentities(input)).toEqual({...input,bookId,unitId});
  expect(normalizeVocabularyIdentities({id:'21953',bookId:'guixue:10177',kind:'group'})).toEqual({id:'ielts-listening-essentials-chapter-01-group-06',bookId:'ielts-listening-essentials',kind:'group'});
  expect(normalizeVocabularyIdentities({sources:[{type:'wordbook',id:'guixue:10174:21795:ve-x',bookId:'guixue:10174',unitId:'21795'}]}).sources[0].id).toBe(`${bookId}:${unitId}:ve-x`);
  expect(normalizeVocabularyRoute('/vocabulary/wordbooks/guixue%3A10174/groups/21795/learn?bookId=guixue%3A10174&unitId=21795')).toBe(`/vocabulary/wordbooks/${bookId}/groups/${unitId}/learn?bookId=${bookId}&unitId=${unitId}`);
});
test('legacy frozen draft and device recovery migrate only the selected account', () => {
  Object.assign(VOCABULARY_CATALOG,JSON.parse(readFileSync('public/vocabulary-catalog.json','utf8')));
  const batch=buildLearningBatch(emptyState(),bookId,unitId,0,1);
  const session=createVocabularySession(batch.cards,batch.mode,{}, {bookId,unitId},batch.selection);
  session.selection={...batch.selection,bookId:'guixue:10174',unitId:'21795'};
  session.filter={...session.filter,bookId:'guixue:10174',unitId:'21795'};
  session.cardSnapshots=session.cardSnapshots!.map(card=>({...card,context:card.context&&{...card.context,bookId:'guixue:10174',unitId:'21795'}}));
  localStorage.setItem('fieldbook-vocabulary-draft-v1:owner',JSON.stringify({version:1,savedAt:new Date().toISOString(),session}));
  expect(readVocabularyDraft('owner')?.selection).toMatchObject({bookId,unitId});
  const pending={viewedEntryIds:['ve-x'],currentEntryId:'ve-x',updatedAt:'2020-01-01',sequence:1};
  const old='fieldbook:vocabulary-learning-pending:owner:guixue:10174:21795';
  localStorage.setItem(old,JSON.stringify(pending));
  localStorage.setItem(old.replace(':owner:',':other:'),JSON.stringify(pending));
  migrateVocabularyRecovery('owner');
  expect(JSON.parse(localStorage.getItem(`fieldbook:vocabulary-learning-pending:owner:${bookId}:${unitId}`)!)).toEqual(pending);
  expect(localStorage.getItem(old)).toBeNull();
  expect(localStorage.getItem(old.replace(':owner:',':other:'))).not.toBeNull();
  const oldPosition='fieldbook:vocabulary-position:owner:/vocabulary/wordbooks/guixue%3A10174';
  sessionStorage.setItem(oldPosition,JSON.stringify({scroll:42,focus:'group-21795',chapters:[{id:'chapter-21794',open:true}]}));
  migrateVocabularyRecovery('owner');
  expect(JSON.parse(sessionStorage.getItem('fieldbook:vocabulary-position:owner:/vocabulary/wordbooks/ielts-vocabulary')!)).toEqual({scroll:42,focus:'group-'+unitId,chapters:[{id:'chapter-ielts-vocabulary-chapter-01',open:true}]});
});
