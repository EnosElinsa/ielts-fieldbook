"""Audit public vocabulary readiness and independently reconstruct dictation identities.

Run from any directory: python scripts/audit-vocabulary-readiness.py [--check]
Reads only checked-in public/catalog and editorial source files. Never reads accounts.
This is a fresh-public-state model, not an execution of the TypeScript runtime and not
an exhaustive editorial review of dictionary polysemy or intended group meanings.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOMAIN = "src/domain/vocabulary/"
OUTPUT_JSON = ROOT / "docs/vocabulary-readiness-audit.json"
OUTPUT_MD = ROOT / "docs/vocabulary-readiness-audit.md"
UNCERTAIN = re.compile(
    r"malformed|unconfirmed|unknown|uncertain|context.*(?:needed|required|missing)|"
    r"(?:source|specific|exact|intended).*(?:unknown|unconfirmed|not.*confirmed)|"
    r"plausible|possibly|inferred|may be intended|not a (?:standard|conventional|usual)|"
    r"original.*(?:unusual|incorrect|incomplete)|spelling (?:error|mistake)|"
    r"(?:conventional|usual|normal|more natural|more common) (?:form|expression|phrase|term)|"
    r"nonstandard|normally say|unusual|fragment", re.I
)
CHINESE = re.compile(r"[\u3400-\u9fff]")
PLACEHOLDER = re.compile(r"definition pending|meaning pending|a phrase referring to|the word is", re.I)


def read(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8-sig"))


def identity(row):
    return row["entryId"], row["senseId"]


def member_key(row):
    return row["bookId"], row["unitId"], row["entryId"]


def present(value):
    return isinstance(value, str) and bool(value.strip())


def render_markdown(report):
    s = report["summary"]
    lines = [
        "# Vocabulary readiness audit", "",
        "Generated by `python scripts/audit-vocabulary-readiness.py` from public release files and checked-in editorial overlays. No accounts, learner notes, imported answers or remote services are read.", "",
        f"Automatic checks cover **{s['entriesScanned']:,} entries, {s['membershipsScanned']:,} memberships and {s['groupsScanned']} dictation groups**. The source additions contain **{s['coreRows']:,} core rows, {s['correctionRows']:,} correction/example rows and {s['readinessDefaults']} preferred defaults**.", "",
        f"Original catalogue defaults lacked definitions for **{s['originalMissingDefinitionEntries']:,}** entries and examples for **{s['originalMissingExampleEntries']:,}**. The public priority model now has **{s['currentMissingDefinitionEntries']}** missing definitions and **{s['currentMissingExampleEntries']}** missing examples in standalone defaults. Group selections have **{s['membershipMissingDefinition']}** missing definitions and **{s['membershipMissingExample']}** missing examples.", "",
        "Coverage means a nonempty selected definition, example and part of speech. It does not certify all meanings, grammar, factual content, synonyms, media or intended source-group senses. Common learner defaults are editorial choices, not proof of group intent. Uncertain or malformed phrases retain usage notes.", "",
        "The independent public model first reconstructs context bindings/defaults and readiness supplements, then applies the released group curriculum: source-specific rows, thematic rows, or common meanings for general lists. Polysemy groups retain their multiple curricular senses while dictation uses the first. Theme/common/multiple recommendations do not verify original source meanings. It models fresh public content only: explicit sense selection, personal edits, history migration and runtime task eligibility require their own tests.", "",
        f"Dictation identity reconstruction passed **{s['dictationGroupsPassed']}/{s['groupsScanned']}** groups: source membership counts, declared counts, entry existence, one selected stable sense per unique entry, and unique `entryId:senseId:dictation` identities. **{s['groupsWithDuplicateMemberships']}** group contains repeated source-word membership; the one-card-per-entry model preserves the source rows and deduplicates the dictation cards. This is an independent Python reconstruction, not a claim that browser sessions were executed. Every group's ordered entry IDs, reconstructed card IDs and duplicate warnings are in the JSON report.", "",
        "| Book | Memberships | Original missing definition | Original missing example | Current missing definition | Current missing example | Core supplemented memberships |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for b in report["books"]:
        lines.append(f"| {b['title']} | {b['memberships']} | {b['originalMissingDefinitionMemberships']} | {b['originalMissingExampleMemberships']} | {b['currentMissingDefinitionMemberships']} | {b['currentMissingExampleMemberships']} | {b['coreSupplementedMemberships']} |")
    lines += ["", "## Scope and remaining uncertainty", "",
              f"The context manifest identifies {s['contextReviewedBindings']} reviewed group bindings, {s['contextUnresolvedBindings']} unresolved bindings, and {s['contextDefaults']} context defaults. These are separate from the {s['coreRows']:,} newly authored missing-content rows and {s['correctionRows']:,} correction/example rows. This audit does not expand a reviewed status to all {s['membershipsScanned']:,} memberships.", "",
              f"Usage-note scanning identified **{s['uncertainOrNonstandardUsageCandidates']}** entries needing care with wording, interpretation or register. These are automatic candidates, not a definitive count of erroneous terms. All notes are retained in the JSON report; a selected core-phrase list follows.", "",
              "| Term | Usage note |", "|---|---|"]
    for row in report["usageCandidates"]:
        if row["source"] == "core":
            lines.append(f"| {row['term'].replace('|', '/')} | {row['usage'].replace('|', '/').replace(chr(10), ' ')} |")
    lines += ["", "## Validation", "", f"Detected structural/content defects: **{len(report['defects'])}**.", "",
              "The JSON includes all selected entry senses, group identities, changed preferred defaults, source-file SHA-256 hashes and structural defects. Source hashes make this report traceable to the actual files scanned. Rerun after overlays change. `--check` verifies the saved reports without rewriting them and exits nonzero for stale reports or structural defects.", "",
              "No claim is made that every dictionary sense or every source group's intended meaning has received editorial review."]
    for defect in report["defects"]:
        lines.append(f"- {json.dumps(defect, ensure_ascii=False)}")
    return "\n".join(lines) + "\n"


def audit():
    paths = ["public/vocabulary-catalog.json", "public/vocabulary-content-manifest.json",
             DOMAIN + "contextSenseOverlay.json", DOMAIN + "learningSenseOverlay.json",
             DOMAIN + "readinessCorrections.json", DOMAIN + "readinessDefaults.json",
             DOMAIN + "readiness.ts", DOMAIN + "context.ts", DOMAIN + "selection.ts"]
    core_paths = [DOMAIN + f"readinessContent{i}.json" for i in range(3)]
    paths += core_paths
    curriculum_paths = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / DOMAIN).glob("groupCurriculum*.json"))
    paths += curriculum_paths + [DOMAIN + "curriculum.ts"]
    data = {p: read(p) for p in paths if p.endswith(".json")}
    catalog = data[paths[0]]
    context = data[DOMAIN + "contextSenseOverlay.json"]
    learning = data[DOMAIN + "learningSenseOverlay.json"]
    core_rows = [r for p in core_paths for r in data[p]]
    correction_rows = data[DOMAIN + "readinessCorrections.json"]
    defaults_rows = data[DOMAIN + "readinessDefaults.json"]
    core = {identity(r): r for r in core_rows}
    corrections = {identity(r): r for r in correction_rows}
    defaults = {r["entryId"]: r for r in defaults_rows}
    entries = {e["id"]: e for e in catalog["entries"]}
    bindings = {member_key(r): r for r in context["bindings"]}
    context_defaults = {r["entryId"]: r for r in context["defaults"]}
    unresolved = {member_key(r) for r in context["unresolved"]}
    units = {(u["bookId"], u["id"]): u for u in catalog["units"]}
    source_curriculum = {member_key(r): r for r in data.get(DOMAIN + "groupCurriculumSource.json", [])}
    topic_rows = [r for p in curriculum_paths if "Topics" in p for r in data[p]]
    topic_curriculum = {member_key(r): r for r in topic_rows}
    common_curriculum = defaultdict(list)
    for row in data.get(DOMAIN + "groupCurriculumCommon.json", []):
        if row["sense"]["id"] not in {r["sense"]["id"] for r in common_curriculum[row["entryId"]]}:
            common_curriculum[row["entryId"]].append(row)
    curriculum_repairs = {(r["entryId"], r["sense"]["id"]): r for r in data.get(DOMAIN + "groupCurriculumRepairs.json", [])}
    modern_curriculum = {r["entryId"]: r for r in data.get(DOMAIN + "groupCurriculumModernDefaults.json", [])}
    defects = []

    def supplement(entry_id, sense):
        result = dict(sense)
        row = corrections.get((entry_id, sense.get("id"))) or core.get((entry_id, sense.get("id")))
        if row:
            for field in ("definition", "example", "pos", "usage"):
                if row.get(field):
                    result[field] = row[field]
        return result

    def fallback_resolve(entry, membership=None):
        binding = bindings.get(member_key(membership)) if membership else None
        binding = binding or context_defaults.get(entry["id"])
        if binding:
            return dict(binding["sense"]), "context-binding" if membership and member_key(membership) in bindings else "context-default"
        candidate = defaults.get(entry["id"])
        base = candidate["sense"] if candidate else learning.get(entry["term"].lower()) or (entry.get("senses") or [{}])[0]
        return supplement(entry["id"], base), "readiness-default" if candidate else "learning-overlay" if entry["term"].lower() in learning else "catalogue"

    def curriculum(entry, membership):
        if not membership:
            return None, []
        unit = units.get((membership["bookId"], membership["unitId"]))
        if not unit or unit["kind"] == "chapter":
            return None, []
        key = member_key(membership)
        source_row, topic_row = source_curriculum.get(key), topic_curriculum.get(key)
        theme = membership["bookId"] == "guixue:10174"
        multiple = membership["bookId"] == "guixue:10177" and unit.get("parentId") == "21954"
        rows = [source_row] if source_row else [topic_row] if topic_row else [] if theme else common_curriculum[entry["id"]] if multiple and common_curriculum[entry["id"]] else [modern_curriculum[entry["id"]]] if entry["id"] in modern_curriculum else common_curriculum[entry["id"]]
        if not rows and not theme:
            fallback, _ = fallback_resolve(entry, membership)
            repair = curriculum_repairs.get((entry["id"], fallback.get("id")))
            rows = [repair] if repair else []
        basis = "source" if source_row else "multiple" if multiple else "theme" if theme else "common"
        return basis, rows if multiple else rows[:1]

    def resolve(entry, membership=None):
        sense, origin = fallback_resolve(entry, membership)
        basis, rows = curriculum(entry, membership)
        return (dict(rows[0]["sense"]), "curriculum-" + basis) if rows else (sense, origin)

    for name, rows, required, key_fn in [
        ("core", core_rows, ("entryId", "senseId", "definition", "example", "pos"), identity),
        ("corrections", correction_rows, ("entryId", "senseId", "example"), identity),
        ("defaults", defaults_rows, ("entryId",), lambda r: r["entryId"]),
    ]:
        counts = Counter(key_fn(r) for r in rows)
        for key, count in counts.items():
            if count > 1:
                defects.append({"type": "duplicate-overlay-identity", "source": name, "identity": key, "count": count})
        for row in rows:
            if row["entryId"] not in entries:
                defects.append({"type": "unknown-overlay-entry", "source": name, "entryId": row["entryId"]})
            for field in required:
                if not present(row.get(field)):
                    defects.append({"type": "missing-overlay-field", "source": name, "entryId": row["entryId"], "field": field})
            sense = row.get("sense", row)
            for field in ("definition", "example", "usage", "pos"):
                text = sense.get(field, "")
                if CHINESE.search(text) or PLACEHOLDER.search(text):
                    defects.append({"type": "language-or-placeholder", "source": name, "entryId": row["entryId"], "field": field})
    if len(core_rows) != 1168:
        defects.append({"type": "unexpected-core-count", "expected": 1168, "actual": len(core_rows)})
    original_missing_ids = {e["id"] for e in catalog["entries"] if not present((e.get("senses") or [{}])[0].get("definition"))}
    if original_missing_ids != set(r["entryId"] for r in core_rows):
        defects.append({"type": "core-original-gap-coverage-mismatch",
                        "missingCoreEntryIds": sorted(original_missing_ids - set(r["entryId"] for r in core_rows)),
                        "nonGapCoreEntryIds": sorted(set(r["entryId"] for r in core_rows) - original_missing_ids)})
    for row in core_rows:
        if row["entryId"] in entries and row["senseId"] not in {s["id"] for s in entries[row["entryId"]].get("senses", [])}:
            defects.append({"type": "core-original-sense-identity-mismatch", "entryId": row["entryId"], "senseId": row["senseId"]})

    entry_rows = []
    for entry in catalog["entries"]:
        original = (entry.get("senses") or [{}])[0]
        current, origin = resolve(entry)
        entry_rows.append({"entryId": entry["id"], "term": entry["term"], "originalSenseId": original.get("id"),
                           "originalMissingDefinition": not present(original.get("definition")), "originalMissingExample": not present(original.get("example")),
                           "selectedSenseId": current.get("id"), "selectionSource": origin, "definition": current.get("definition", ""),
                           "example": current.get("example", ""), "pos": current.get("pos", ""), "usage": current.get("usage", ""),
                           "missingDefinition": not present(current.get("definition")), "missingExample": not present(current.get("example")),
                           "missingPos": not present(current.get("pos")), "senseChanged": original.get("id") != current.get("id")})
    by_entry = {r["entryId"]: r for r in entry_rows}
    membership_rows = []
    grouped = defaultdict(list)
    for m in catalog["memberships"]:
        grouped[(m["bookId"], m["unitId"])].append(m)
        entry = entries.get(m["entryId"])
        if not entry:
            defects.append({"type": "unknown-membership-entry", "membershipId": m.get("id"), "entryId": m["entryId"]})
            continue
        sense, origin = resolve(entry, m)
        basis, curriculum_rows = curriculum(entry, m)
        selected_binding = bindings.get(member_key(m))
        source_confirmed = any(r.get("sectionId") and r.get("sentenceIds") for r in curriculum_rows if r["sense"]["id"] == sense.get("id"))
        status = "reviewed" if source_confirmed else selected_binding["status"] if selected_binding and selected_binding["sense"]["id"] == sense.get("id") else "unresolved" if member_key(m) in unresolved else "unreviewed"
        membership_rows.append({"bookId": m["bookId"], "unitId": m["unitId"], "entryId": m["entryId"], "senseId": sense.get("id"),
                                "membershipId": m.get("id"), "term": entry["term"], "curriculumBasis": basis,
                                "curriculumSenseIds": [r["sense"]["id"] for r in curriculum_rows] or [sense.get("id")],
                                "curriculumAuthored": bool(curriculum_rows), "sourceMeaningVerified": bool(source_confirmed),
                                "definition": sense.get("definition", ""), "example": sense.get("example", ""), "pos": sense.get("pos", ""),
                                "selectionSource": origin, "missingDefinition": not present(sense.get("definition")),
                                "missingExample": not present(sense.get("example")), "missingPos": not present(sense.get("pos")),
                                "contextStatus": status})
    groups = []
    for unit in catalog["units"]:
        if unit["kind"] != "group":
            continue
        ms = sorted(grouped[(unit["bookId"], unit["id"])], key=lambda m: (m.get("order", 0), m["entryId"]))
        ids = [m["entryId"] for m in ms]
        card_ids = []
        group_defects = []
        group_warnings = []
        for m in ms:
            if m["entryId"] in entries:
                sense, _ = resolve(entries[m["entryId"]], m)
                if present(sense.get("id")):
                    card_ids.append(f"{m['entryId']}:{sense['id']}:dictation")
                else:
                    group_defects.append("missing-selected-sense-id")
            else:
                group_defects.append("unknown-entry")
        declared = unit.get("totalSourceWords", len(ms))
        if len(ms) != declared:
            group_defects.append("declared-membership-count-mismatch")
        duplicate_ids = sorted({entry_id for entry_id in ids if ids.count(entry_id) > 1})
        if duplicate_ids:
            group_warnings.append({"type": "duplicate-entry-membership", "entryIds": duplicate_ids,
                                   "detail": "Source membership repeats a word; dictation reconstructs one card per unique entry."})
        card_ids = list(dict.fromkeys(card_ids))
        if len(card_ids) != len(set(ids)) or len(card_ids) != len(set(card_ids)):
            group_defects.append("card-identity-count-mismatch")
        row = {"bookId": unit["bookId"], "unitId": unit["id"], "title": unit["title"], "declaredWords": declared,
               "memberships": len(ms), "uniqueEntryIds": len(set(ids)), "reconstructedDictationCards": len(card_ids),
               "orderedEntryIds": ids, "cardIds": card_ids, "passed": not group_defects, "defects": group_defects, "warnings": group_warnings}
        groups.append(row)
        if group_defects:
            defects.append({"type": "dictation-group-identity", "bookId": unit["bookId"], "unitId": unit["id"], "defects": group_defects})
    if len(groups) != 165:
        defects.append({"type": "unexpected-group-count", "expected": 165, "actual": len(groups)})
    books = []
    core_ids = {r["entryId"] for r in core_rows}
    for book in catalog["books"]:
        ms = [m for m in membership_rows if m["bookId"] == book["id"]]
        unique = {m["entryId"] for m in ms}
        books.append({"bookId": book["id"], "title": book["title"], "memberships": len(ms), "uniqueEntries": len(unique),
                      "declaredSourceWords": book.get("totalSourceWords"), "originalMissingDefinitionMemberships": sum(by_entry[m["entryId"]]["originalMissingDefinition"] for m in ms),
                      "originalMissingExampleMemberships": sum(by_entry[m["entryId"]]["originalMissingExample"] for m in ms),
                      "currentMissingDefinitionMemberships": sum(m["missingDefinition"] for m in ms), "currentMissingExampleMemberships": sum(m["missingExample"] for m in ms),
                      "currentMissingPosMemberships": sum(m["missingPos"] for m in ms), "coreSupplementedMemberships": sum(m["entryId"] in core_ids for m in ms),
                      "coreSupplementedUniqueEntries": len(unique & core_ids), "dictationGroups": sum(g["bookId"] == book["id"] for g in groups)})
    usage_candidates = []
    for name, rows in [("core", core_rows), ("correction", correction_rows), ("default", defaults_rows)]:
        for row in rows:
            sense = row.get("sense", row)
            if UNCERTAIN.search(sense.get("usage", "")):
                usage_candidates.append({"source": name, "entryId": row["entryId"], "term": entries.get(row["entryId"], {}).get("term", ""),
                                         "senseId": sense.get("id", row.get("senseId")), "usage": sense["usage"]})
    summary = {"entriesScanned": len(entry_rows), "membershipsScanned": len(catalog["memberships"]), "groupsScanned": len(groups),
               "coreRows": len(core_rows), "coreUniqueEntries": len(core_ids), "coreRowsByFile": {p: len(data[p]) for p in core_paths}, "correctionRows": len(correction_rows),
               "correctionUniqueEntries": len({r['entryId'] for r in correction_rows}), "readinessDefaults": len(defaults_rows),
               "originalMissingDefinitionEntries": sum(r["originalMissingDefinition"] for r in entry_rows), "originalMissingExampleEntries": sum(r["originalMissingExample"] for r in entry_rows),
               "currentMissingDefinitionEntries": sum(r["missingDefinition"] for r in entry_rows), "currentMissingExampleEntries": sum(r["missingExample"] for r in entry_rows),
               "currentMissingPosEntries": sum(r["missingPos"] for r in entry_rows), "membershipMissingDefinition": sum(r["missingDefinition"] for r in membership_rows),
               "membershipMissingExample": sum(r["missingExample"] for r in membership_rows), "membershipMissingPos": sum(r["missingPos"] for r in membership_rows),
               "dictationGroupsPassed": sum(g["passed"] for g in groups), "groupsWithDuplicateMemberships": sum(bool(g["warnings"]) for g in groups),
               "contextReviewedBindings": sum(r["status"] == "reviewed" for r in context["bindings"]),
               "contextUnresolvedBindings": len(context["unresolved"]), "contextDefaults": len(context["defaults"]),
               "uncertainOrNonstandardUsageCandidates": len(usage_candidates), "structuralDefects": len(defects)}
    summary["curriculumRowsByFile"] = {p: len(data[p]) for p in curriculum_paths}
    summary["curriculumMembershipsByBasis"] = dict(sorted(Counter(m["curriculumBasis"] for m in membership_rows).items()))
    return {"schemaVersion": 1, "scope": "Automatic public fresh-state coverage and identity scan; authored overlays are separate from exhaustive semantic/context review.",
            "privateDataRead": False, "sourceHashes": {p: hashlib.sha256((ROOT / p).read_bytes().replace(b'\r\n', b'\n')).hexdigest() for p in paths},
            "summary": summary, "books": books, "groups": groups, "entries": entry_rows, "memberships": membership_rows,
            "defaultChanges": [{"entryId": r["entryId"], "oldSenseId": r.get("originalSense", {}).get("id"), "selectedSense": r["sense"]} for r in defaults_rows],
            "usageCandidates": usage_candidates, "defects": defects}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check committed reports without rewriting them")
    args = parser.parse_args()
    report = audit()
    json_text = json.dumps(report, indent=2, ensure_ascii=False) + "\n"
    md_text = render_markdown(report)
    if args.check:
        if not OUTPUT_JSON.exists() or not OUTPUT_MD.exists() or OUTPUT_JSON.read_text(encoding="utf-8") != json_text or OUTPUT_MD.read_text(encoding="utf-8") != md_text:
            print("Readiness reports are missing or stale; rerun without --check.")
            return 1
    else:
        OUTPUT_JSON.write_text(json_text, encoding="utf-8")
        OUTPUT_MD.write_text(md_text, encoding="utf-8")
    print(json.dumps(report["summary"], indent=2))
    return int(bool(report["defects"]))


if __name__ == "__main__":
    raise SystemExit(main())
